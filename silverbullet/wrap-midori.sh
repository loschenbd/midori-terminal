#!/bin/sh
# Wrap silverbullet/midori.css for one of SilverBullet's two injection routes
# and write the result to stdout. This script NEVER writes into a space, a data
# folder or a project directory -- it only renders, and you decide where the
# output goes. That is deliberate: SilverBullet spaces are real project folders
# (~/Projects/<project>), and nothing in this repo may drop a markdown page into
# one of those.
#
#   sh silverbullet/wrap-midori.sh --space-style   > "Midori Theme.md"
#   sh silverbullet/wrap-midori.sh --head-html     # a JSON string for spaces.json
#
# POSIX sh. See silverbullet/README.md for which route to pick.

set -eu

CSS="${CSS:-$(dirname "$0")/midori.css}"

usage() {
	cat >&2 <<'EOF'
usage: wrap-midori.sh (--space-style | --head-html)

  --space-style  a markdown page whose body is a space-style fenced block;
                 save it anywhere in the space and the client picks it up
  --head-html    a JSON-encoded <style> element for the "headHtml" key of a
                 space in spaces.json
EOF
	exit 2
}

[ $# -eq 1 ] || usage

[ -f "$CSS" ] || {
	echo "wrap-midori.sh: no stylesheet at $CSS" >&2
	exit 1
}

bytes=$(wc -c < "$CSS" | tr -d ' ')
[ "$bytes" -gt 0 ] || {
	echo "wrap-midori.sh: $CSS is empty -- refusing to emit an empty theme" >&2
	exit 1
}

# TWO TRUNCATION GUARDS, both checked for BOTH routes, because a stylesheet
# that cannot be installed one way is a bug either way.
#
# 1. ``` -- under --space-style the whole stylesheet goes inside a fenced
#    block, and a fence ends at the first line that opens with a run of
#    backticks at least as long as the opening fence.
# 2. </style -- under --head-html it goes inside a <style> element, and an
#    HTML parser ends that element at the first `</style`, whatever follows.
#    silverbullet-hub's installer refuses such CSS outright.
#
# Either one truncates the installed theme SILENTLY: the page still renders,
# the block or element still parses, and there is nothing to notice except
# missing colour further down.
if grep -n '```' "$CSS" >&2; then
	echo "wrap-midori.sh: the lines above contain a triple backtick." >&2
	echo "  A space-style fence would end there, truncating the theme." >&2
	echo "  Write \`space-style\` with single backticks instead." >&2
	exit 1
fi

if grep -n '</style' "$CSS" >&2; then
	echo "wrap-midori.sh: the lines above contain '</style'." >&2
	echo "  The headHtml <style> element would end there, truncating the" >&2
	echo "  theme, and silverbullet-hub refuses CSS containing it." >&2
	exit 1
fi

case "$1" in
--space-style)
	cat <<'EOF'
---
tags: [meta, theme]
---
# Midori Theme

Midori Paper and Night for this space. Generated by
`silverbullet/wrap-midori.sh --space-style` in the midori-terminal repo; edit
the stylesheet there and regenerate rather than editing this page, or the two
drift apart with no way to tell which is current.

The client collects every `space-style` object in the space, orders them by
`priority` descending, wraps each in its own `<style>`, and writes the lot into
`<div id="custom-styles">` at the end of `<body>`. Note what that ordering
means for CSS: a HIGHER priority lands EARLIER in the document, so it loses
same-specificity ties to any lower-priority block. This block declares no
priority, and the only other `space-style` block in a stock space is the
Library's one-rule `.sb-video-embed` reset, so nothing here is contested.

```space-style
EOF
	cat "$CSS"
	printf '```\n'
	;;
--head-html)
	# JSON-encode via python3 so quoting, newlines and backslashes in the CSS
	# cannot break spaces.json. There is no sh-only way to do this safely.
	command -v python3 >/dev/null 2>&1 || {
		echo "wrap-midori.sh: --head-html needs python3 to encode JSON safely" >&2
		exit 1
	}
	CSS="$CSS" python3 -c 'import json,os,sys
css = open(os.environ["CSS"], encoding="utf-8").read()
sys.stdout.write(json.dumps("<style>\n" + css + "</style>"))
sys.stdout.write("\n")'
	;;
*)
	usage
	;;
esac

echo "wrap-midori.sh: wrapped $bytes bytes from $CSS" >&2
